%RUN_DIMENSIONLESS_LOGSPACING_FIRST_RESULT_PIPELINE Log-spaced enzyme sweep.
%
% From repo root:
%   matlab -batch "run('scripts/run_dimensionless_logspacing_first_result_pipeline.m')"
%
% Identical to run_dimensionless_first_result_pipeline.m EXCEPT the enzyme
% sweep is log-spaced (enzyme_spacing='log'). This is the direct comparison
% variant for the linear-vs-log E* resolution question raised in the audit
% (docs/MODEL_AUDIT.md 5.4). Writes to separate dirs so the existing
% linear-spacing dimensionless result is NOT overwritten.

setup_repo_paths();
tStart = tic;

mode = 'paper_inspired_dimensionless';
resultDir = fullfile('results', 'dimensionless_logspacing_first_result');
figureDir = fullfile('figures', 'dimensionless_logspacing_first_result');
screenFile = fullfile(resultDir, 'results_deterministic_screen.csv');
selectedFile = fullfile(resultDir, 'selected_parameter_sets.csv');
ssaFile = fullfile(resultDir, 'results_ssa_kl.csv');
exampleFile = fullfile(resultDir, 'ssa_example_E0_E1_distributions.csv');
summaryFile = fullfile(resultDir, 'summary.md');

fprintf('\n=== Dimensionless first-result pipeline (LOG-SPACED enzyme sweep) ===\n');

run_deterministic_screen( ...
    'mode', mode, ...
    'enzyme_spacing', 'log', ...
    'N_runs', 500, ...
    'n_E_vals', 100, ...
    'useParallel', true, ...
    'outputFile', screenFile, ...
    'randomSeed', 1);

select_parameter_sets( ...
    'inputFile', screenFile, ...
    'N_select', 60, ...
    'oversampleFactor', 1.5, ...
    'outputFile', selectedFile, ...
    'randomSeed', 2, ...
    'stratifyBy', 'average_phi');

run_ssa_kl_on_selected( ...
    'mode', mode, ...
    'inputFile', selectedFile, ...
    'N_stoch', 100, ...
    't_end_stoch', 25, ...
    'nBins', 10, ...
    'useParallel', true, ...
    'batchSize', 10, ...
    'outputFile', ssaFile, ...
    'randomSeed', 3, ...
    'exampleDistributionFile', exampleFile);

plot_pipeline_results( ...
    'mode', mode, ...
    'screenFile', screenFile, ...
    'ssaFile', ssaFile, ...
    'exampleDistributionFile', exampleFile, ...
    'outputDir', figureDir);

plot_response_curves( ...
    'mode', mode, ...
    'enzyme_spacing', 'log', ...
    'selectedFile', selectedFile, ...
    'screenFile', screenFile, ...
    'outputFile', fullfile(figureDir, 'fig_example_response_curves.png'));

write_pipeline_summary(screenFile, selectedFile, ssaFile, summaryFile, struct( ...
    'name', "dimensionless_logspacing_first_result", ...
    'notes', ["Mode: paper_inspired_dimensionless, enzyme_spacing=LOG (comparison variant)."; ...
              "Units: ATP=1, RT=1; phi and delta_mu in kBT-like units."; ...
              "Rate ranges symmetric 10^-2..10^2; E0=0.95*E*, E1=1.05*E*; E sweep log-spaced."; ...
              "Settings: N_runs=500, n_E_vals=100, N_select=60 (oversample 1.5), N_stoch=100, t_end_stoch=25, nBins=10."; ...
              "Compare summary.md and fig_JS_vs_phi.png against results/dimensionless_first_result (linear)."]));

fprintf('\nLog-spacing dimensionless first-result finished in %.1f minutes.\n', toc(tStart)/60);
fprintf('Deliverables: %s, %s, summary.md\n', resultDir, figureDir);
