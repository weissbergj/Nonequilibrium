%RUN_DIMENSIONLESS_FIRST_RESULT_PIPELINE Practical first dimensionless result.
%
% From repo root:
%   matlab -batch "run('scripts/run_dimensionless_first_result_pipeline.m')"
%
% Paper-inspired dimensionless enzyme-model analogy. Bounded and practical:
% this is NOT a 10k x SSA brute force and does NOT use t_end_stoch=1500.
% Expected runtime: roughly 15-60 minutes depending on CPU and parallel pool.

setup_repo_paths();
tStart = tic;

mode = 'paper_inspired_dimensionless';
resultDir = fullfile('results', 'dimensionless_first_result');
figureDir = fullfile('figures', 'dimensionless_first_result');
screenFile = fullfile(resultDir, 'results_deterministic_screen.csv');
selectedFile = fullfile(resultDir, 'selected_parameter_sets.csv');
ssaFile = fullfile(resultDir, 'results_ssa_kl.csv');
exampleFile = fullfile(resultDir, 'ssa_example_E0_E1_distributions.csv');
summaryFile = fullfile(resultDir, 'summary.md');

fprintf('\n=== Dimensionless first-result pipeline (paper-inspired) ===\n');

run_deterministic_screen( ...
    'mode', mode, ...
    'N_runs', 500, ...
    'n_E_vals', 100, ...
    'useParallel', true, ...
    'outputFile', screenFile, ...
    'randomSeed', 1);

select_parameter_sets( ...
    'inputFile', screenFile, ...
    'N_select', 60, ...
    'oversampleFactor', 1.5, ...
    'outputFile', selectedFile, ...
    'randomSeed', 2, ...
    'stratifyBy', 'average_phi');

run_ssa_kl_on_selected( ...
    'mode', mode, ...
    'inputFile', selectedFile, ...
    'N_stoch', 100, ...
    't_end_stoch', 25, ...
    'nBins', 10, ...
    'useParallel', true, ...
    'batchSize', 10, ...
    'outputFile', ssaFile, ...
    'randomSeed', 3, ...
    'exampleDistributionFile', exampleFile);

plot_pipeline_results( ...
    'mode', mode, ...
    'screenFile', screenFile, ...
    'ssaFile', ssaFile, ...
    'exampleDistributionFile', exampleFile, ...
    'outputDir', figureDir);

plot_response_curves( ...
    'mode', mode, ...
    'selectedFile', selectedFile, ...
    'screenFile', screenFile, ...
    'outputFile', fullfile(figureDir, 'fig_example_response_curves.png'));

write_pipeline_summary(screenFile, selectedFile, ssaFile, summaryFile, struct( ...
    'name', "dimensionless_first_result", ...
    'notes', ["Mode: paper_inspired_dimensionless (enzyme-model analogy, NOT the PNAS Markov model)."; ...
              "Units: ATP=1, RT=1; phi and delta_mu are in kBT-like units."; ...
              "Rate ranges symmetric 10^-2..10^2; E0=0.95*E*, E1=1.05*E*."; ...
              "Settings: N_runs=500, n_E_vals=100, N_select=60 (oversample 1.5), N_stoch=100, t_end_stoch=25, nBins=10."; ...
              "Headline metric: JS divergence (bounded). Raw KL kept for continuity but can saturate near -ln(epsilon)~34."; ...
              "Keep t_end_stoch bounded; only raise after SSA feasibility and steady-state checks."]));

fprintf('\nDimensionless first-result pipeline finished in %.1f minutes.\n', toc(tStart)/60);
fprintf('Deliverables for researcher: %s, %s, summary.md\n', resultDir, figureDir);
