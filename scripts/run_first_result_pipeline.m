%RUN_FIRST_RESULT_PIPELINE Practical first scientific run (not 48h brute-force).
%
% From repo root:
%   matlab -batch "run('scripts/run_first_result_pipeline.m')"
%
% Expected runtime: roughly 30-90 minutes depending on CPU and parallel pool.

setup_repo_paths();
tStart = tic;

resultDir = fullfile('results', 'first_result');
figureDir = fullfile('figures', 'first_result');
screenFile = fullfile(resultDir, 'results_deterministic_screen.csv');
selectedFile = fullfile(resultDir, 'selected_parameter_sets.csv');
ssaFile = fullfile(resultDir, 'results_ssa_kl.csv');
exampleFile = fullfile(resultDir, 'ssa_example_E0_E1_distributions.csv');
summaryFile = fullfile(resultDir, 'summary.md');

fprintf('\n=== First-result pipeline ===\n');

run_deterministic_screen( ...
    'N_runs', 500, ...
    'n_E_vals', 100, ...
    'useParallel', true, ...
    'outputFile', screenFile, ...
    'randomSeed', 1);

select_parameter_sets( ...
    'inputFile', screenFile, ...
    'N_select', 50, ...
    'oversampleFactor', 1.5, ...
    'outputFile', selectedFile, ...
    'randomSeed', 2, ...
    'stratifyBy', 'average_phi');

run_ssa_kl_on_selected( ...
    'inputFile', selectedFile, ...
    'N_stoch', 50, ...
    't_end_stoch', 25, ...
    'nBins', 10, ...
    'useParallel', true, ...
    'batchSize', 10, ...
    'outputFile', ssaFile, ...
    'randomSeed', 3, ...
    'exampleDistributionFile', exampleFile);

plot_pipeline_results( ...
    'screenFile', screenFile, ...
    'ssaFile', ssaFile, ...
    'exampleDistributionFile', exampleFile, ...
    'outputDir', figureDir);

write_pipeline_summary(screenFile, selectedFile, ssaFile, summaryFile, struct( ...
    'name', "first_result", ...
    'notes', ["Settings: N_runs=500, n_E_vals=100, N_select=50 (oversample 1.5), N_stoch=50, t_end_stoch=25, nBins=10."; ...
              "Use valid_for_kl rows only for KL-vs-energy interpretation."; ...
              "Do not increase t_end_stoch to 1500 until SSA feasibility is confirmed."]));

fprintf('\nFirst-result pipeline finished in %.1f minutes.\n', toc(tStart)/60);
fprintf('Deliverables for researcher: %s, %s, summary.md\n', resultDir, figureDir);
